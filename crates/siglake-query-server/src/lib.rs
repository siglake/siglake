struct SecurityAddon;

impl utoipa::Modify for SecurityAddon {
    fn modify(&self, openapi: &mut utoipa::openapi::OpenApi) {
        use utoipa::openapi::security::{HttpAuthScheme, HttpBuilder, SecurityScheme};
        // utoipa 5's `components(...)` attribute accepts only `schemas` and
        // `responses`, so a security scheme has to be added through a
        // `Modify` impl. `get_or_insert_default` because `components` may be
        // None before any schema is collected.
        openapi
            .components
            .get_or_insert_default()
            .add_security_scheme(
                "query_token",
                SecurityScheme::Http(
                    HttpBuilder::new()
                        .scheme(HttpAuthScheme::Bearer)
                        .description(Some(
                            "`Authorization: Bearer <token>`. With OIDC configured the \
                             token is a JWT and its claims select the tenant; otherwise it \
                             is matched against the cluster's static token list. A server \
                             started with neither accepts unauthenticated requests.",
                        ))
                        .build(),
                ),
            );
    }
}

/// Unauthenticated routes.
///
/// Split from [`api_routes`] because these must sit *outside* the auth,
/// in-flight-tracking and latency-stamping `route_layer`s.
