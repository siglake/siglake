/// Server-side per-tier ceilings. Per-request overrides clamp against
/// these — a request can ask for less but never more.
///
/// `max_rows` lives outside the per-tier structure for backward compat
/// with chunk-1 callers; it is the *interactive* tier's row cap (and
/// applies when no `Priority` is set). The full per-tier ceilings
/// live in `interactive` / `batch`.
#[derive(Debug, Clone)]
pub struct ServerLimits {
    pub max_rows: usize,
    pub interactive: TierLimits,
    pub batch: TierLimits,
    /// Per-process query admission budget, shared by interactive requests and
    /// asynchronous batch jobs. Tunable via
    /// `SIGLAKE_QUERY_ADMISSION_BUDGET_BYTES` in Helm/env. Batch jobs stay on
    /// their detached CPU runtime but reserve a fixed quarter of this budget;
    /// interactive reservations use a cost-derived share capped at a quarter
    /// by default. Overflow submissions get 429 rather than oversubscribing the
    /// process-wide memory pool.
    pub admission_budget_bytes: u64,
    /// Multiplier applied to `estimated_bytes_scanned` when reserving
    /// interactive admission bytes. Tunable via
    /// `SIGLAKE_QUERY_ADMISSION_DECOMPRESSION_FACTOR`; models decoded working
    /// set rather than compressed Parquet bytes.
    pub admission_decompression_factor: u64,
    /// How long an interactive query or batch submission will wait for
    /// admission before returning 429. Tunable via
    /// `SIGLAKE_QUERY_ADMISSION_WAIT_MS`.
    pub admission_wait_timeout: std::time::Duration,
}

impl Default for ServerLimits {
    fn default() -> Self {
        // The interactive mid-flight breaker ceilings are operator-tunable: the
        // 100M-row / 100GB defaults suit ~50G datasets, but a legitimately large
        // scan at scale (e.g. a 25% time-window aggregate over 400M rows ≈ 98M
        // rows) trips the fixed row cap → 413 instead of degrading to slow. Sizing
        // for the dataset (rows ≈ a few × the largest expected windowed scan)
        // lets those queries complete; the wall-clock timeout + admission budget
        // still bound runaway work. The batch tier keeps its much higher ceilings.
        let mut interactive = TierLimits::interactive_defaults();
        if let Some(v) = std::env::var("SIGLAKE_QUERY_CEILING_ROWS_SCANNED")
            .ok()
            .and_then(|v| v.parse::<usize>().ok())
            .filter(|n| *n > 0)
        {
            interactive.ceiling_rows_scanned = v;
        }
        if let Some(gb) = std::env::var("SIGLAKE_QUERY_CEILING_BYTES_SCANNED_GB")
            .ok()
            .and_then(|v| v.parse::<u64>().ok())
            .filter(|n| *n > 0)
        {
            interactive.ceiling_bytes_scanned = gb.saturating_mul(1024 * 1024 * 1024);
        }
        Self {
            max_rows: 1_000_000,
            interactive,
            batch: TierLimits::batch_defaults(),
            admission_budget_bytes: std::env::var("SIGLAKE_QUERY_ADMISSION_BUDGET_BYTES")
                .ok()
                .and_then(|v| v.parse().ok())
                .unwrap_or_else(default_admission_budget_bytes),
            admission_decompression_factor: std::env::var(
                "SIGLAKE_QUERY_ADMISSION_DECOMPRESSION_FACTOR",
            )
            .ok()
            .and_then(|v| v.parse().ok())
            .filter(|n: &u64| *n > 0)
            .unwrap_or(4),
            admission_wait_timeout: std::env::var("SIGLAKE_QUERY_ADMISSION_WAIT_MS")
                .ok()
                .and_then(|v| v.parse().ok())
                .map(std::time::Duration::from_millis)
                .unwrap_or_else(|| std::time::Duration::from_secs(2)),
        }
    }
}

impl ServerLimits {
    /// Effective tier limits for `priority`, with the global
    /// [`ServerLimits::max_rows`] cap folded in (it can only tighten,
    /// never loosen, the tier ceiling).
    pub fn tier(&self, priority: Priority) -> TierLimits {
        let mut t = match priority {
            Priority::Interactive => self.interactive.clone(),
            Priority::Batch => self.batch.clone(),
        };
        t.ceiling_rows_returned = t.ceiling_rows_returned.min(self.max_rows);
        t
    }
}

