// ---- SSE stream ------------------------------------------------------------

/// `GET /api/v1/stream` — Server-Sent Events tail of the ingest path.
///
/// Published from the ingest path BEFORE the WAL append, not after
/// acknowledgement: the ingester tees each batch to subscribers ahead of the
/// append, on both the backpressure and direct write paths. So a tailed event
/// is not yet accepted — a batch the ingester then refuses for backlog
/// (`503`) or whose append fails (`500`) has already reached every subscriber
/// with no durable row behind it, and the caller's retry publishes those
/// events a second time. Only the `events` index is teed; writes to user
/// indexes never appear on the tail.
///
/// Push-only, best-effort: a subscriber that falls behind by
/// `STREAM_BROADCAST_CAPACITY` events loses the events, not the
/// subscription — it stays connected and receives an event named `lagged`
/// whose data is the number of dropped events, so a lag burst leaves a
/// reported gap rather than ending the stream. No history; no
/// durability. For replayable subscriptions use the
/// Iceberg-incremental `siglake subscribe` path. Server-side filtering was
/// removed with SPL — filter client-side or use the subscribe path.
#[utoipa::path(
    get,
    path = "/api/v1/stream",
    tag = "stream",
    params(
        // THE HEADER IS THE SUBSCRIPTION. Everywhere else on the ingest path an
        // absent tenant header means "write into `default`", which a caller
        // notices when they query for their own rows; here it means "deliver
        // ANOTHER tenant's events", and nothing in the exchange surfaces it —
        // the stream returns 200, keeps alive, and never completes. So this
        // parameter says what is selected, not just what it defaults to.
        ("x-scope-orgid" = Option<String>, Header,
         description = "Tenant whose events this subscription delivers, \
                        `[A-Za-z0-9_-]{1,128}`. Absent ⇒ `default`: the subscription \
                        succeeds and delivers the `default` tenant's events, so a \
                        missing header is silent — it selects a different tenant's \
                        stream rather than failing. When the ingester derives the \
                        tenant from a verified JWT claim (`--oidc-tenant-claim`) this \
                        header may only AGREE with the claim; disagreeing is `403`."),
    ),
    responses(
        (status = 200, description = "SSE stream. Each `data:` line is one JSON \
            `Event`. A subscriber that falls behind receives an event named \
            `lagged` whose data is the number of dropped events. A keep-alive \
            comment is sent every 15 seconds. The stream never completes.",
         content_type = "text/event-stream", body = String),
        (status = 400, description = "Invalid `X-Scope-OrgID` value \
            (`[A-Za-z0-9_-]{1,128}`), refused by the ingest middleware before the \
            subscription is created.", body = SiglakeErrorBody),
        (status = 401, description = "Missing or invalid credentials.", body = SiglakeErrorBody),
        (status = 403, description = "Tenant refused: this ingester is \
            single-tenant and the header named another tenant, or the header \
            disagrees with (or the token lacks) the JWT tenant claim, or the resolved \
            tenant is outside `--allowed-tenants`, or this ingester is at \
            `--max-tenants` and the resolved tenant is one it has not admitted \
            before.", body = SiglakeErrorBody),
        (status = 429, description = "Rate limited.", body = RateLimitBody,
         headers(("retry-after" = u64, description = "Seconds to wait before retrying."))),
        (status = 500, description = "Streaming is not enabled on this ingester.",
         body = SiglakeErrorBody),
    ),
)]
async fn get_stream(
    State(state): State<AppState>,
    tenant: Option<axum::extract::Extension<ResolvedTenant>>,
) -> Result<Sse<impl Stream<Item = Result<SseEvent, Infallible>>>, ApiError> {
    let tenant = tenant
        .as_ref()
        .map(|resolved| resolved.0 .0.clone())
        .unwrap_or_else(|| DEFAULT_TENANT.to_string());
    let tx = state
        .events_tx
        .as_ref()
        .ok_or_else(|| ApiError::internal("streaming is not enabled on this ingester"))?;
    let mut rx = tx.subscribe();
    metrics::counter!("siglake_ingest_stream_subscribers_opened_total").increment(1);

    let s = stream! {
        loop {
            match rx.recv().await {
                Ok(streamed) => {
                    // TENANT SCOPE. One process-wide broadcast carries every
                    // lane's events, so without this a subscriber receives every
                    // tenant's `raw` -- the full log line, the highest-value data
                    // in the system -- and cannot even tell whose it is.
                    //
                    // This bounds a subscriber to the tenant it asked for. What
                    // it does NOT do is decide whether the caller may ask for
                    // that tenant: the header is the sole authority for that,
                    // here as everywhere on the ingest path. Binding the tenant
                    // to a verified identity is a separate control, and this
                    // filter is what makes that control mean something for the
                    // stream.
                    if streamed.tenant != tenant {
                        continue;
                    }
                    let json = serde_json::to_string(&streamed.event).unwrap_or_default();
                    yield Ok(SseEvent::default().data(json));
                }
                Err(broadcast::error::RecvError::Lagged(n)) => {
                    metrics::counter!("siglake_ingest_stream_lagged_total")
                        .increment(n);
                    // Signal lag to the subscriber and continue.
                    yield Ok(SseEvent::default()
                        .event("lagged")
                        .data(format!("{n}")));
                }
                Err(broadcast::error::RecvError::Closed) => break,
            }
        }
    };
    Ok(Sse::new(s).keep_alive(KeepAlive::new().interval(Duration::from_secs(15))))
}

// ---- Error response shape --------------------------------------------------

struct ApiError {
    status: StatusCode,
    msg: String,
    retry_after_secs: Option<u64>,
}

impl ApiError {
    fn bad_request(msg: impl Into<String>) -> Self {
        Self {
            status: StatusCode::BAD_REQUEST,
            msg: msg.into(),
            retry_after_secs: None,
        }
    }

    /// 403, not 401: the caller IS authenticated — they are just not this
    /// tenant. Answering 401 would invite a client to retry with different
    /// credentials for a request that will never be allowed.
    fn forbidden(msg: impl Into<String>) -> Self {
        Self {
            status: StatusCode::FORBIDDEN,
            msg: msg.into(),
            retry_after_secs: None,
        }
    }

    fn unauthorized(msg: impl Into<String>) -> Self {
        Self {
            status: StatusCode::UNAUTHORIZED,
            msg: msg.into(),
            retry_after_secs: None,
        }
    }

    fn service_unavailable(retry_after_secs: u64, msg: impl Into<String>) -> Self {
        Self {
            status: StatusCode::SERVICE_UNAVAILABLE,
            msg: msg.into(),
            retry_after_secs: Some(retry_after_secs),
        }
    }

    fn gateway_timeout(msg: impl Into<String>) -> Self {
        Self {
            status: StatusCode::GATEWAY_TIMEOUT,
            msg: msg.into(),
            retry_after_secs: None,
        }
    }

    fn es(status: StatusCode, error_type: &'static str, reason: impl Into<String>) -> Self {
        Self {
            status,
            msg: serde_json::json!({
                "error": {
                    "type": error_type,
                    "reason": reason.into(),
                },
                "status": status.as_u16(),
            })
            .to_string(),
            retry_after_secs: None,
        }
    }

    fn internal(e: impl std::fmt::Display) -> Self {
        Self {
            status: StatusCode::INTERNAL_SERVER_ERROR,
            msg: format!("{e:#}"),
            retry_after_secs: None,
        }
    }
}

impl IntoResponse for ApiError {
    fn into_response(self) -> Response {
        let is_es_body = self.msg.starts_with("{\"error\"");
        let mut resp = if is_es_body {
            let mut resp = Response::new(Body::from(self.msg));
            *resp.status_mut() = self.status;
            resp.headers_mut()
                .insert(CONTENT_TYPE, HeaderValue::from_static("application/json"));
            resp
        } else {
            let body = serde_json::json!({"text": self.msg, "code": self.status.as_u16()});
            (self.status, Json(body)).into_response()
        };
        if let Some(retry_after_secs) = self.retry_after_secs {
            resp.headers_mut().insert(
                axum::http::header::RETRY_AFTER,
                HeaderValue::from(retry_after_secs),
            );
        }
        resp
    }
}

