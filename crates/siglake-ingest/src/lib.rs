#[tracing::instrument(
    skip_all,
    fields(endpoint = %endpoint, tenant = %tenant_id, index = %index_id, event_count = batch.num_rows())
)]
async fn ingest_batch(
    state: &AppState,
    tenant_id: &str,
    index_id: &str,
    batch: RecordBatch,
    commit_mode: CommitMode,
    endpoint: &'static str,
) -> Result<CommitReceipt, ApiError> {
    if let Some(bp) = state.backpressure.as_ref() {
        // The SSE tail is teed BEFORE the batch reaches the WAL, here and on
        // the direct path below; `submit_for_index_with_commit` consumes
        // `batch`, so this is also the last point it can be read. A batch
        // then refused for backlog (`503`) or whose append fails (`500`) has
        // already reached subscribers with no durable row behind it, and the
        // caller's retry publishes it again — documented on `get_stream`.
        if index_id == EVENTS_INDEX_ID {
            tee_batch(state, tenant_id, &batch);
        }
        let outcome = bp
            .submit_for_index_with_commit(tenant_id, index_id, batch, commit_mode)
            .await;
        let receipt = match outcome {
            backpressure::SubmitOutcome::Accepted(receipt) => receipt,
            backpressure::SubmitOutcome::Backpressure { retry_after_secs } => {
                metrics::counter!("siglake_ingest_backpressure_rejected_total",
                    "endpoint" => endpoint, "tenant" => tenant_label(tenant_id), "index" => index_label(index_id))
                    .increment(1);
                return Err(ApiError::service_unavailable(
                    retry_after_secs,
                    "Service Unavailable: ingester backlog full",
                ));
            }
            backpressure::SubmitOutcome::Failed(e) => return Err(ApiError::internal(e)),
        };
        wait_for_force_commit(
            commit_mode,
            state.commit_force_timeout,
            receipt.force_segment.as_deref(),
            state.wal_is_mirrored().await,
            state.remote_wal_drain,
        )
        .await?;
        return Ok(receipt);
    }

    let (writer_arc, _, _) = state
        .writer_for_index_request(Some(tenant_id), Some(index_id))
        .await
        .map_err(ApiError::internal)?;
    let mut writer = writer_arc.lock().await;
    // Ahead of the append, as above.
    if index_id == EVENTS_INDEX_ID {
        tee_batch(state, tenant_id, &batch);
    }
    let receipt =
        append_batch_with_commit(&mut writer, &batch, commit_mode).map_err(ApiError::internal)?;
    // Read `has_mirror` from the guard we ALREADY hold, and drop the guard
    // before the force-commit wait. Asking `AppState` would re-lock this same
    // writer and self-deadlock; and holding the writer across a wait of up to
    // `commit_force_timeout` would block every other append to this lane.
    let mirrored = writer.has_mirror();
    drop(writer);
    wait_for_force_commit(
        commit_mode,
        state.commit_force_timeout,
        receipt.force_segment.as_deref(),
        mirrored,
        state.remote_wal_drain,
    )
    .await?;
    Ok(receipt)
}

trait CommitWalWriter {
    fn append_for_commit(&mut self, batch: &RecordBatch) -> Result<Option<PathBuf>>;
    fn sync_active_for_commit(&mut self) -> Result<bool>;
    fn seal_for_commit(&mut self) -> Result<Option<PathBuf>>;
}

impl CommitWalWriter for WalWriter {
    fn append_for_commit(&mut self, batch: &RecordBatch) -> Result<Option<PathBuf>> {
        Ok(self.append_batch(batch)?.map(|segment| segment.path))
    }

    fn sync_active_for_commit(&mut self) -> Result<bool> {
        self.sync_active()
    }

    fn seal_for_commit(&mut self) -> Result<Option<PathBuf>> {
        Ok(self.seal()?.map(|segment| segment.path))
    }
}

fn append_batches_with_commit<'a>(
    writer: &mut impl CommitWalWriter,
    batches: impl IntoIterator<Item = &'a RecordBatch>,
    commit_mode: CommitMode,
) -> Result<CommitReceipt> {
    let mut sealed = None;
    for batch in batches {
        if batch.num_rows() != 0 {
            sealed = writer.append_for_commit(batch)?;
        }
    }
    let force_segment = match commit_mode {
        CommitMode::Auto => None,
        // `append_batch` flushes to the OS page cache but does not fsync.
        // `wait_for` therefore syncs the active partial file before acking when
        // the append did not already seal (and thus fsync) the segment.
        CommitMode::WaitFor => {
            if sealed.is_none() {
                writer.sync_active_for_commit()?;
            }
            None
        }
        // `force` exists for tests and benchmarks, not hot paths: seal the
        // active segment immediately, then the caller polls until the compactor
        // moves that filename out of `sealed/` and `processing/`.
        CommitMode::Force => {
            if sealed.is_some() {
                sealed
            } else {
                writer.seal_for_commit()?
            }
        }
    };
    Ok(CommitReceipt { force_segment })
}

fn append_batch_with_commit(
    writer: &mut WalWriter,
    batch: &RecordBatch,
    commit_mode: CommitMode,
) -> Result<CommitReceipt> {
    append_batches_with_commit(writer, std::iter::once(batch), commit_mode)
}

async fn wait_for_force_commit(
    commit_mode: CommitMode,
    timeout: Duration,
    force_segment: Option<&Path>,
    mirrored: bool,
    remote_wal_drain: bool,
) -> Result<(), ApiError> {
    if commit_mode != CommitMode::Force {
        return Ok(());
    }
    // `commit=force` proves commit by watching the segment leave the LOCAL
    // sealed/processing directories. That proof remains valid when a local
    // drain also mirrors the WAL. A remote drain instead commits from object
    // storage and never moves the ingester's local file.
    //
    // Refuse up front instead. A truthful 400 naming the reason beats a 30s
    // wait and a false negative, and `commit=wait_for` remains available.
    if mirrored && remote_wal_drain {
        metrics::counter!("siglake_ingest_commit_force_unsupported_total").increment(1);
        return Err(ApiError::bad_request(
            "commit=force is not supported when a remote drain consumes the mirrored WAL: the \
             segment is committed from object storage, so this ingester cannot observe the \
             commit. Use commit=wait_for (fsync the WAL) and query for visibility, or use \
             a local drain.",
        ));
    }
    let start = Instant::now();
    let Some(segment) = force_segment else {
        metrics::histogram!("siglake_ingest_commit_force_wait_seconds")
            .record(start.elapsed().as_secs_f64());
        return Ok(());
    };
    loop {
        if !segment_pending_commit(segment).map_err(ApiError::internal)? {
            metrics::histogram!("siglake_ingest_commit_force_wait_seconds")
                .record(start.elapsed().as_secs_f64());
            return Ok(());
        }
        if start.elapsed() >= timeout {
            metrics::histogram!("siglake_ingest_commit_force_wait_seconds")
                .record(start.elapsed().as_secs_f64());
            return Err(commit_timeout_response(
                "force",
                format!(
                    "commit=force timed out after {}s waiting for segment `{}` to leave sealed/processing",
                    timeout.as_secs().max(1),
                    segment
                        .file_name()
                        .and_then(|name| name.to_str())
                        .unwrap_or("unknown"),
                ),
            ));
        }
        tokio::time::sleep(Duration::from_millis(50)).await;
    }
}

fn segment_pending_commit(segment: &Path) -> Result<bool> {
    let name = segment
        .file_name()
        .ok_or_else(|| anyhow::anyhow!("segment has no filename: {}", segment.display()))?;
    let wal_dir = segment
        .parent()
        .and_then(|parent| parent.parent())
        .ok_or_else(|| anyhow::anyhow!("segment is not under a WAL dir: {}", segment.display()))?;
    Ok(wal_dir.join(SEALED_DIR).join(name).exists()
        || wal_dir.join(PROCESSING_DIR).join(name).exists())
}

/// `Retry-After` (seconds) advertised when the memory circuit breaker sheds a
/// request. Roughly the compactor's drain cadence — long enough for RSS to
/// recede, short enough that a well-behaved client retries promptly.
const MEM_BREAKER_RETRY_AFTER_SECS: u64 = 5;

fn mem_breaker_api_error() -> ApiError {
    ApiError::service_unavailable(
        MEM_BREAKER_RETRY_AFTER_SECS,
        "Service Unavailable: ingester over memory limit",
    )
}

/// Count one request shed by the memory circuit breaker, once, on whichever
/// transport refused it. Both counters are read by shipped consumers:
/// `siglake_ingest_requests_total{status="503"}` feeds the ingester's KEDA
/// trigger and the operator's offered-load query, and
/// `siglake_ingest_mem_breaker_rejected_total{endpoint}` is how an operator
/// tells a breaker refusal from a backpressure one. Until task #3876 the gRPC
/// exporters shed without touching either, so a gRPC-only deployment moved
/// only the `siglake_ingest_mem_breaker_open` gauge.
fn record_mem_breaker_refusal(endpoint: &'static str) {
    metrics::counter!("siglake_ingest_requests_total",
        "endpoint" => endpoint, "status" => "503")
    .increment(1);
    metrics::counter!("siglake_ingest_mem_breaker_rejected_total",
        "endpoint" => endpoint)
    .increment(1);
}

/// The gRPC counterpart of [`mem_breaker_response`]: same accounting, same
/// `ApiError`, mapped to `UNAVAILABLE` with the `retry-after` metadata.
fn mem_breaker_grpc_status(endpoint: &'static str) -> Status {
    record_mem_breaker_refusal(endpoint);
    api_error_to_grpc_status(mem_breaker_api_error())
}

/// Build the `503 Service Unavailable` shed response for the memory circuit
/// breaker, mirroring the backpressure path's body + `Retry-After` shape.
fn mem_breaker_response(endpoint: &'static str) -> Response {
    record_mem_breaker_refusal(endpoint);
    let err = mem_breaker_api_error();
    let body = serde_json::json!({
        "text": err.msg,
        "code": err.status.as_u16(),
        "retry_after_secs": MEM_BREAKER_RETRY_AFTER_SECS,
    });
    let mut resp = (err.status, Json(body)).into_response();
    resp.headers_mut().insert(
        axum::http::header::RETRY_AFTER,
        axum::http::HeaderValue::from(MEM_BREAKER_RETRY_AFTER_SECS),
    );
    resp
}

