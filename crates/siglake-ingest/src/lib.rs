async fn post_otlp_logs(
    State(state): State<AppState>,
    Query(commit): Query<CommitQuery>,
    headers: HeaderMap,
    tenant: Option<axum::extract::Extension<ResolvedTenant>>,
    body: Bytes,
) -> Result<Response, ApiError> {
    let _in_flight = InFlightGuard::new("otlp");
    let start = Instant::now();
    let index_id = resolve_request_index(&headers)?;
    let commit_mode = resolve_commit_mode(
        commit,
        headers
            .get(COMMIT_HEADER)
            .and_then(|value| value.to_str().ok()),
    )
    .map_err(ApiError::bad_request)?;
    // WS-8 memory circuit breaker: shed load *before* the parse work when RSS
    // is over the configured ceiling, so a backlog can't drive the pod OOM.
    if let Some(guard) = state.mem_guard.as_ref() {
        if guard.is_over_limit() {
            return Ok(mem_breaker_response("otlp"));
        }
    }
    let format = OtlpContentType::from_headers(&headers);
    let bad_request = |kind: &str, e: String| {
        metrics::counter!("siglake_ingest_requests_total",
            "endpoint" => "otlp", "status" => "400")
        .increment(1);
        ApiError::bad_request(format!("invalid OTLP {kind}: {e}"))
    };
    // Parse + map inside each arm so the owned buffer outlives the borrowing
    // parse: simd-json (SIMD, in-situ) deserializes into structs that borrow
    // attribute keys + string values straight from `buf` (zero-copy), and the
    // mapping appends them into the Arrow builders while `buf` is still alive
    // — no per-event owned `Event` detour. The arm yields the built
    // `RecordBatch`, so nothing borrows past it.
    let batch = match format {
        OtlpContentType::Json => {
            let mut buf = body.to_vec();
            let request = otlp::parse_otlp_json(&mut buf).map_err(|e| bad_request("JSON", e))?;
            otlp::otlp_logs_to_record_batch(request).map_err(ApiError::internal)?
        }
        OtlpContentType::Protobuf => {
            let request = otlp::decode_export_logs_service_request_protobuf(body.as_ref())
                .map_err(|e| bad_request("protobuf", e))?;
            otlp::otlp_logs_to_record_batch(request).map_err(ApiError::internal)?
        }
    };
    let n = batch.num_rows();
    tracing::Span::current().record("event_count", n);
    metrics::histogram!("siglake_ingest_request_events", "endpoint" => "otlp").record(n as f64);
    metrics::counter!("siglake_ingest_commit_total", "mode" => commit_mode.as_label()).increment(1);
    let tenant_id = tenant
        .as_ref()
        .map(|resolved| resolved.0 .0.clone())
        .unwrap_or_else(|| DEFAULT_TENANT.to_string());
    ingest_batch(&state, &tenant_id, &index_id, batch, commit_mode, "otlp").await?;
    finish_accepted_request(
        "otlp",
        &tenant_id,
        &index_id,
        start,
        n,
        format.success_response_kind(),
    )
}

