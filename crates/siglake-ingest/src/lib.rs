fn metadata_ascii<'a>(metadata: &'a tonic::metadata::MetadataMap, key: &str) -> Option<&'a str> {
    metadata.get(key).and_then(|value| value.to_str().ok())
}

/// The tenant metadata of a gRPC export, in the shape the shared tenancy
/// boundary reads. Unlike [`metadata_ascii`], a present-but-unreadable value
/// stays distinguishable from an absent one — it is a refusal, not a write to
/// the default tenant.
fn metadata_scope_header(metadata: &tonic::metadata::MetadataMap) -> ScopeHeader<'_> {
    match metadata.get(TENANT_HEADER) {
        None => ScopeHeader::Absent,
        Some(value) => match value.to_str() {
            Ok(raw) => ScopeHeader::Value(raw),
            Err(_) => ScopeHeader::Unreadable,
        },
    }
}

fn grpc_invalid_argument(msg: String) -> Status {
    Status::invalid_argument(msg)
}

fn api_error_to_grpc_status(err: ApiError) -> Status {
    let code = match err.status {
        StatusCode::BAD_REQUEST => Code::InvalidArgument,
        StatusCode::UNAUTHORIZED => Code::Unauthenticated,
        StatusCode::SERVICE_UNAVAILABLE => Code::Unavailable,
        StatusCode::GATEWAY_TIMEOUT => Code::DeadlineExceeded,
        StatusCode::INTERNAL_SERVER_ERROR => Code::Internal,
        _ => Code::Unknown,
    };
    let mut status = Status::new(code, err.msg);
    if let Some(retry_after_secs) = err.retry_after_secs {
        if let Ok(value) = retry_after_secs.to_string().parse() {
            status.metadata_mut().insert("retry-after", value);
        }
    }
    status
}

