    #[tokio::test(flavor = "current_thread")]
    async fn sse_tee_precedes_backpressure_rejection() {
        const REJECTED_RAW: &str = "uniquely-rejected-sse-event";

        let tmp = tempfile::tempdir().unwrap();
        let writer = WalWriter::with_thresholds(
            tmp.path(),
            "unused-direct-writer",
            10,
            Duration::from_secs(60),
        )
        .unwrap();
        let backpressure = backpressure::BackpressureRouter::new(
            tmp.path(),
            "test-backpressure-writer",
            10,
            Duration::from_secs(60),
            1,
        );
        let state = AppState::with_streaming(writer).with_backpressure(backpressure);
        let mut subscriber = state.events_tx.as_ref().unwrap().subscribe();
        let router = state.backpressure.as_ref().unwrap().clone();

        // `tokio::spawn` does not synchronously poll the new writer task. Polling
        // this submission inline therefore fills the capacity-1 lane and leaves
        // it there until this current-thread test yields to the runtime.
        let mut queued = Box::pin(router.submit(
            DEFAULT_TENANT,
            vec![test_event("lane-filler-bypasses-the-sse-tee")],
        ));
        {
            let waker = futures::task::noop_waker();
            let mut cx = std::task::Context::from_waker(&waker);
            assert!(std::future::Future::poll(queued.as_mut(), &mut cx).is_pending());
        }

        let error = match ingest_events(
            &state,
            DEFAULT_TENANT,
            EVENTS_INDEX_ID,
            vec![test_event(REJECTED_RAW)],
            CommitMode::Auto,
            "test",
        )
        .await
        {
            Err(error) => error,
            Ok(_) => panic!("the full backpressure lane accepted a second batch"),
        };
        let response = error.into_response();
        assert_eq!(response.status(), StatusCode::SERVICE_UNAVAILABLE);
        assert_eq!(response.headers()[axum::http::header::RETRY_AFTER], "1");

        let streamed = subscriber
            .try_recv()
            .expect("the rejected event must be teed before the full-lane check");
        assert_eq!(streamed.tenant, DEFAULT_TENANT);
        assert_eq!(streamed.event.raw, REJECTED_RAW);
        assert!(matches!(
            subscriber.try_recv(),
            Err(broadcast::error::TryRecvError::Empty)
        ));

        assert!(matches!(
            queued.await,
            backpressure::SubmitOutcome::Accepted(_)
        ));
        router.shutdown().await;
    }

