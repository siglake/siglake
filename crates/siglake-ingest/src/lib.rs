/// Bearer-token allow-list for ingest auth. Empty (or `None` on
/// `AppState`) means every request is accepted — the open-mode v0
/// behavior, only safe inside a trusted network.
///
/// Auth is decoupled from tenancy: a request's tenant comes from the
/// `X-Scope-OrgID` header (see [`sanitize_tenant`]), not from which
/// token it carries. A token grants access to *all* tenants; restrict
/// per-tenant access at the gateway/mesh if you need it.
#[derive(Debug, Default, Clone)]
pub struct AuthTokens {
    tokens: HashSet<String>,
}

impl AuthTokens {
    /// Parse a CSV of bearer tokens (`"tok1,tok2"`). Blank entries are
    /// dropped; surrounding whitespace is trimmed.
    pub fn from_csv(csv: &str) -> Self {
        Self::from_tokens(csv.split(','))
    }

    /// Construct from a collection of tokens.
    pub fn from_tokens<I, S>(tokens: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        let tokens = tokens
            .into_iter()
            .filter_map(|t| {
                let t = t.into().trim().to_string();
                (!t.is_empty()).then_some(t)
            })
            .collect();
        Self { tokens }
    }

    pub fn is_empty(&self) -> bool {
        self.tokens.is_empty()
    }

    pub fn matches(&self, token: &str) -> bool {
        self.tokens.contains(token)
    }
}

/// Router that maps a tenant identifier to its [`WalWriter`].
///
/// Per-tenant writers live under `<root>/<tenant>/` so each tenant
/// gets a private `active/`, `sealed/`, `processing/`, `committed/`
/// directory tree. The compactor reads the same layout: it discovers
/// tenants by listing the top-level children of `<root>/` and
/// processes each tenant's `sealed/` independently, committing to
/// the matching Iceberg namespace.
///
/// Writers are lazily created on first event for the tenant. The
/// `default` writer is created up-front (the [`AppState::with_streaming`]
/// constructor uses this path) so single-tenant deployments behave
/// identically to pre-4.10c.
pub struct TenantWalRouter {
    root: PathBuf,
    ingester_id: String,
    max_events: usize,
    max_age: Duration,
    writers: tokio::sync::Mutex<HashMap<TenantIndexKey, Arc<Mutex<WalWriter>>>>,
    mirror_handle: tokio::sync::Mutex<Option<siglake_wal::mirror::WalMirrorHandle>>,
    /// #2693: resolves the Iceberg table behind a lane, so each writer stamps
    /// its segments with the table they are destined for. `None` in the
    /// deployments and tests that have no catalog to ask.
    identity: tokio::sync::Mutex<Option<Arc<dyn WalTableIdentity>>>,
    /// When each lane's identity was last resolved, so the refresh is a
    /// per-lane metadata read on an interval rather than one per request.
    identity_checked: tokio::sync::Mutex<HashMap<TenantIndexKey, Instant>>,
}

/// Resolves the Iceberg table identity behind a `(tenant, index)` ingest lane.
///
/// The WAL directory is keyed by the index NAME, which a `DELETE`+`POST` of the
/// same id reuses for a different table. A writer that stamps its segments has
/// to learn that identity from somewhere, and `siglake-ingest` deliberately
/// does not link `siglake-storage` — the binary that hosts both (the `ingest`
/// command, which opens an `IcebergContext` at startup for exactly this kind of
/// reason) supplies the implementation.
#[async_trait::async_trait]
pub trait WalTableIdentity: Send + Sync {
    /// The table UUID behind `(tenant, index)` right now, or `None` when the
    /// name resolves to no table (yet — the drain auto-creates on first
    /// commit). An error leaves the writer's current binding in place.
    async fn table_uuid(&self, tenant: &str, index: &str) -> Result<Option<uuid::Uuid>>;
}

/// How long a lane's bound identity is trusted before it is re-resolved.
/// Override with `SIGLAKE_WAL_IDENTITY_REFRESH_SECS`; `0` disables the refresh
/// (the binding is then resolved once, at writer creation).
pub const DEFAULT_IDENTITY_REFRESH: Duration = Duration::from_secs(30);

/// Pure resolver for [`DEFAULT_IDENTITY_REFRESH`]'s env override.
///
/// This is the window in which a recreated index's ingest is still stamped with
/// the DROPPED table's uuid: those rows are acked, then held under `stale/`
/// rather than committed. Shortening it costs one catalog metadata read per
/// lane per interval.
pub fn identity_refresh_from(raw: Option<&str>) -> Duration {
    raw.and_then(|v| v.trim().parse::<u64>().ok())
        .map(Duration::from_secs)
        .unwrap_or(DEFAULT_IDENTITY_REFRESH)
}

fn identity_refresh() -> Duration {
    identity_refresh_from(
        std::env::var("SIGLAKE_WAL_IDENTITY_REFRESH_SECS")
            .ok()
            .as_deref(),
    )
}

impl TenantWalRouter {
    pub fn new(
        root: impl Into<PathBuf>,
        ingester_id: impl Into<String>,
        max_events: usize,
        max_age: Duration,
    ) -> Self {
        Self {
            root: root.into(),
            ingester_id: ingester_id.into(),
            max_events,
            max_age,
            writers: tokio::sync::Mutex::new(HashMap::new()),
            mirror_handle: tokio::sync::Mutex::new(None),
            identity: tokio::sync::Mutex::new(None),
            identity_checked: tokio::sync::Mutex::new(HashMap::new()),
        }
    }

    /// Install the table-identity resolver (#2693) and bind every writer that
    /// is already open. Called once at startup, before the listener binds.
    pub async fn set_identity_resolver(&self, resolver: Option<Arc<dyn WalTableIdentity>>) {
        *self.identity.lock().await = resolver;
        self.identity_checked.lock().await.clear();
        self.refresh_table_identities().await;
    }

    /// Re-resolve every open lane's table whose binding is older than
    /// [`identity_refresh`], and rebind the writer where it changed.
    ///
    /// This is what closes the loop on a `DELETE`+`POST`: without it a writer
    /// opened before the recreation would keep stamping the dropped table's
    /// uuid for as long as the process lives, and every segment it sealed would
    /// be held under `stale/` instead of committed. The rebind seals the open
    /// segment under the previous identity first — those rows WERE written for
    /// the dropped table.
    pub async fn refresh_table_identities(&self) {
        let Some(resolver) = self.identity.lock().await.clone() else {
            return;
        };
        let ttl = identity_refresh();
        let lanes: Vec<(TenantIndexKey, Arc<Mutex<WalWriter>>)> = {
            let writers = self.writers.lock().await;
            writers
                .iter()
                .map(|(k, w)| (k.clone(), w.clone()))
                .collect()
        };
        for (key, writer) in lanes {
            {
                let checked = self.identity_checked.lock().await;
                if let Some(at) = checked.get(&key) {
                    if ttl.is_zero() || at.elapsed() < ttl {
                        continue;
                    }
                }
            }
            let uuid = match resolver.table_uuid(&key.tenant, &key.index).await {
                Ok(u) => u,
                Err(e) => {
                    // Keep the current binding: a catalog blip must not
                    // re-attribute rows, and an unresolved lane is retried on
                    // the next tick.
                    metrics::counter!("siglake_wal_identity_resolve_failures_total").increment(1);
                    tracing::warn!(tenant = %key.tenant, index = %key.index, error = %e,
                        "could not resolve this lane's table identity; keeping the current binding");
                    continue;
                }
            };
            match writer.lock().await.bind_table_uuid(uuid) {
                Ok(Some(seg)) => tracing::info!(
                    tenant = %key.tenant, index = %key.index, rows = seg.rows,
                    "sealed the open WAL segment under the previous table before rebinding"
                ),
                Ok(None) => {}
                Err(e) => {
                    tracing::warn!(tenant = %key.tenant, index = %key.index, error = %e,
                        "WAL identity rebind failed");
                    continue;
                }
            }
            self.identity_checked
                .lock()
                .await
                .insert(key, Instant::now());
        }
    }

    /// Whether a mirror is attached — see [`siglake_wal::WalWriter::has_mirror`].
    pub async fn has_mirror(&self) -> bool {
        self.mirror_handle.lock().await.is_some()
    }

    /// Attach (or remove) a mirror handle. Applied to every
    /// currently-open writer plus every future writer created by
    /// [`Self::writer_for`].
    pub async fn set_mirror_handle(
        &self,
        handle: Option<siglake_wal::mirror::WalMirrorHandle>,
    ) -> anyhow::Result<()> {
        *self.mirror_handle.lock().await = handle.clone();
        let writers = self.writers.lock().await;
        for w in writers.values() {
            w.lock().await.set_mirror_handle(handle.clone());
        }
        Ok(())
    }

    /// Per-tenant root dir: `<root>/<tenant>/`.
    pub fn tenant_dir(&self, tenant: &str) -> PathBuf {
        self.root.join(tenant)
    }

    /// Per-(tenant, index) WAL dir. `events` stays at `<root>/<tenant>/` so the
    /// events-only stream tail, detector, and hot-path WAL readers remain on the
    /// historical layout.
    pub fn index_dir(&self, tenant: &str, index: &str) -> PathBuf {
        if index == EVENTS_INDEX_ID {
            self.tenant_dir(tenant)
        } else {
            self.tenant_dir(tenant).join(index)
        }
    }

    pub fn root(&self) -> &std::path::Path {
        &self.root
    }

    /// Get (or lazily create) the writer for `tenant`.
    pub async fn writer_for(&self, tenant: &str) -> anyhow::Result<Arc<Mutex<WalWriter>>> {
        self.writer_for_index(tenant, EVENTS_INDEX_ID).await
    }

    /// Get (or lazily create) the writer for one `(tenant, index)` lane.
    pub async fn writer_for_index(
        &self,
        tenant: &str,
        index: &str,
    ) -> anyhow::Result<Arc<Mutex<WalWriter>>> {
        let key = TenantIndexKey {
            tenant: tenant.to_string(),
            index: index.to_string(),
        };
        // Fast path.
        {
            let writers = self.writers.lock().await;
            if let Some(w) = writers.get(&key) {
                return Ok(w.clone());
            }
        }
        // Slow path: open a new writer under the tenant's events root or its
        // per-index subdirectory. The identity is resolved BEFORE the write
        // lock — it is a catalog metadata read, and holding the writer map
        // across it would serialize every other lane behind one round trip.
        let resolver = self.identity.lock().await.clone();
        let resolved = match resolver {
            Some(resolver) => match resolver.table_uuid(tenant, index).await {
                Ok(uuid) => Some(uuid),
                Err(e) => {
                    metrics::counter!("siglake_wal_identity_resolve_failures_total").increment(1);
                    tracing::warn!(tenant, index, error = %e,
                        "could not resolve this lane's table identity; its segments carry none \
                         until the next refresh");
                    None
                }
            },
            None => None,
        };
        let mut writers = self.writers.lock().await;
        if let Some(w) = writers.get(&key) {
            return Ok(w.clone());
        }
        let dir = self.index_dir(tenant, index);
        // Durable creation (#3048): these directories come into being before
        // the writer that acknowledges rows into them, so they are the ones
        // that have to carry the fsync of their parent.
        if index != EVENTS_INDEX_ID {
            siglake_wal::create_wal_dir(&self.tenant_dir(tenant).join(SEALED_DIR)).with_context(
                || {
                    format!(
                        "creating tenant discovery dir {}",
                        self.tenant_dir(tenant).display()
                    )
                },
            )?;
        }
        siglake_wal::create_wal_dir(&dir)
            .with_context(|| format!("creating tenant WAL dir {}", dir.display()))?;
        let mut writer = WalWriter::with_thresholds(
            &dir,
            self.ingester_id.clone(),
            self.max_events,
            self.max_age,
        )
        .with_context(|| format!("opening tenant WAL at {}", dir.display()))?;
        let mirror_subdir = if index == EVENTS_INDEX_ID {
            tenant.to_string()
        } else {
            format!("{tenant}/{index}")
        };
        writer.set_mirror_subdir(Some(mirror_subdir));
        if let Some(h) = self.mirror_handle.lock().await.clone() {
            writer.set_mirror_handle(Some(h));
        }
        // #2693: bind the table BEFORE the first append, so no segment this
        // writer opens is ever missing the identity of the rows in it.
        if let Some(uuid) = resolved {
            writer.bind_table_uuid(uuid)?;
            self.identity_checked
                .lock()
                .await
                .insert(key.clone(), Instant::now());
        }
        let arc = Arc::new(Mutex::new(writer));
        writers.insert(key, arc.clone());
        Ok(arc)
    }

    /// Periodic age-roll across every active tenant writer.
    pub async fn tick_all(&self) {
        let snap = {
            let writers = self.writers.lock().await;
            writers.values().cloned().collect::<Vec<_>>()
        };
        for w in snap {
            let mut g = w.lock().await;
            if let Err(e) = g.tick() {
                tracing::warn!(error = %e, "tenant WAL tick failed");
            }
        }
    }

    /// Force-seal every active tenant writer's current segment. Used on
    /// graceful shutdown (the non-backpressure path) so buffered-but-young
    /// segments aren't stranded in `active/` on ingester scale-down —
    /// `tick_all` only age-rolls, which wouldn't seal a fresh segment.
    pub async fn seal_all(&self) {
        let snap = {
            let writers = self.writers.lock().await;
            writers.values().cloned().collect::<Vec<_>>()
        };
        for w in snap {
            let mut g = w.lock().await;
            match g.seal() {
                Ok(Some(seg)) => tracing::info!(
                    rows = seg.rows,
                    "sealed active tenant WAL segment on shutdown"
                ),
                Ok(None) => {}
                Err(e) => tracing::warn!(error = %e, "tenant WAL seal-on-shutdown failed"),
            }
        }
    }

    /// Snapshot of every open writer — used by the active-mirror
    /// loop to flush every tenant per tick.
    pub async fn writers_snapshot(&self) -> Vec<Arc<Mutex<WalWriter>>> {
        let writers = self.writers.lock().await;
        writers.values().cloned().collect()
    }
}

/// The distinct tenants this process has let in, and the gate that decides
/// whether one more fits under [`AppState::max_tenants`].
///
/// A tenant is admitted once, at the tenancy boundary, and stays admitted for
/// the life of the process: a tenant at capacity keeps writing, and it is only
/// a NOVEL tenant that the cap turns away. The set is the reason the decision
/// is a set membership rather than a count of lanes — one tenant writing to
/// twelve indexes is one tenant, and `--ingest-max-lanes` is the bound on the
/// cross product.
///
/// Deliberately process-local, and empty at startup: the cap is per-ingester,
/// like `--ingest-max-lanes`, and an ingester that restarts with tenant
/// directories on disk re-admits them in the order they next write. It is a
/// resource bound on this process, not a cluster-wide tenant registry.
///
/// The lock is a `std::sync::Mutex` and the critical section holds no await:
/// "is this tenant known, and if not is there room" has to be one decision, or
/// two concurrent novel tenants both read `len() < max` and both get in.
#[derive(Clone, Default)]
pub struct TenantAdmission {
    admitted: Arc<std::sync::Mutex<HashSet<String>>>,
}

impl std::fmt::Debug for TenantAdmission {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("TenantAdmission")
            .field("admitted", &self.len())
            .finish()
    }
}

impl TenantAdmission {
    /// Admit `tenant` against a cap of `max` distinct tenants, `0` = unbounded.
    ///
    /// `true` when the tenant may write: it was already admitted, or it was
    /// novel and there was room (in which case it is now admitted). `false`
    /// only for a novel tenant at a full cap — the caller refuses it without
    /// creating anything.
    ///
    /// Unbounded records nothing: tracking every tenant name to enforce no
    /// bound would be the same unbounded growth the cap exists to stop.
    pub fn admit(&self, tenant: &str, max: usize) -> bool {
        if max == 0 {
            return true;
        }
        let mut admitted = self.lock();
        if admitted.contains(tenant) {
            return true;
        }
        if admitted.len() >= max {
            return false;
        }
        admitted.insert(tenant.to_string());
        true
    }

    /// How many distinct tenants have been admitted. Always 0 under an
    /// unbounded cap, which records nothing.
    pub fn len(&self) -> usize {
        self.lock().len()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    /// A poisoned admission set still holds a valid tenant set: the guarded
    /// section is a lookup and an insert with nothing to leave half-done, so a
    /// panic elsewhere must not turn the cap into an outage for every tenant.
    fn lock(&self) -> std::sync::MutexGuard<'_, HashSet<String>> {
        self.admitted
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    }
}

/// State shared across the ingest handlers.
#[derive(Clone)]
pub struct AppState {
    /// Default (single-tenant fallback) writer. Always used when
    /// [`Self::tenants`] is `None` — back-compat with pre-4.10c
    /// callers. When `tenants` is set, this writer is unused.
    pub writer: Arc<Mutex<WalWriter>>,
    /// Per-tenant WAL router. When `Some`, every accepted request
    /// routes to `tenants.writer_for(&resolved_tenant)` instead of
    /// `writer`.
    pub tenants: Option<Arc<TenantWalRouter>>,
    /// Tenants this ingester will accept. `None` = any, the historical
    /// behaviour.
    ///
    /// A tenant id is a CLIENT HEADER, and each novel value mints a backpressure
    /// lane holding an open file, a fresh set of metric label values, and
    /// downstream an Iceberg namespace with seven tables and their metadata
    /// objects. Nothing capped or evicted any of that, so one header could
    /// exhaust an ingester's file descriptors, collapse Prometheus with
    /// cardinality, and grow the catalog without bound — in the default
    /// configuration, since the rate limiter is off by default.
    ///
    /// An allowlist is the bound that costs nothing when you know your tenants.
    /// [`AppState::max_tenants`] is the backstop for when you do not.
    pub allowed_tenants: Option<Arc<std::collections::HashSet<String>>>,
    /// Where the tenant comes from when no verified claim supplies it.
    /// [`TenantRouting::SingleTenant`] by default — see that type for why.
    pub tenant_routing: TenantRouting,
    /// Distinct tenants this ingester will mint before refusing new ones.
    /// `0` = unbounded (the historical behaviour).
    ///
    /// A blunt instrument on purpose: it does not decide WHICH tenants are
    /// real, only that an unbounded stream of invented ones cannot take the
    /// process down. Refusing the 10,001st tenant is a bad day; running out of
    /// file descriptors is an outage for the 10,000 that were real.
    ///
    /// Enforced by [`authorize_tenant`] against [`Self::tenant_admission`], on
    /// the resolved tenant and before anything is created for it.
    pub max_tenants: usize,
    /// The tenants [`Self::max_tenants`] has already admitted on this process.
    /// Shared across every clone of this state, so the two transports and every
    /// concurrent request decide against one count.
    pub tenant_admission: TenantAdmission,
    /// Optional mpsc-fed per-tenant writer router (Phase 4.12.14).
    /// When `Some`, the ingest handlers route through here instead of
    /// `tenants` / `writer`. The handler `try_send`s into a bounded
    /// channel and returns 503 + `Retry-After` on backpressure
    /// rather than blocking on a per-tenant `Mutex<WalWriter>`. Opt-in;
    /// `None` preserves the historical mutex-serialized behavior.
    pub backpressure: Option<Arc<backpressure::BackpressureRouter>>,
    /// Broadcast channel used by SSE subscribers. Optional so callers
    /// (notably unit tests) can opt out of the streaming machinery.
    pub events_tx: Option<broadcast::Sender<StreamedEvent>>,
    /// Ingest token allow-list. `None` ⇒ no auth (the v0 default).
    pub tokens: Option<Arc<AuthTokens>>,
    /// OIDC verifier. When `Some`, every request must carry a valid JWT
    /// signed by the configured issuer. Takes precedence over `tokens`.
    pub oidc_verifier: Option<Arc<OidcVerifier>>,
    /// Per-token (or per-IP, in open mode) token-bucket rate limiter.
    /// `None` ⇒ no rate limiting. As of Phase 4.12.17 this is a
    /// trait object so the in-memory `RateLimiter` and the
    /// Redis-backed `RedisRateBudget` are interchangeable at the
    /// call site.
    pub rate_limiter: Option<Arc<dyn rate_limit::RateBudget>>,
    /// Optional RSS memory circuit breaker (WS-8). When `Some` and the
    /// sampled RSS is over its limit, ingest handlers shed load with
    /// `503` + `Retry-After` before doing parse work. `None` ⇒ no breaker.
    pub mem_guard: Option<Arc<mem_guard::MemoryGuard>>,
    /// Upper bound on how long `commit=force` waits for the compactor to move a
    /// just-sealed segment out of `sealed/` and `processing/`.
    pub commit_force_timeout: Duration,
    /// Whether the configured drain consumes mirrored WAL segments remotely.
    /// Defaults to `true` in callers that do not explicitly know the topology.
    pub remote_wal_drain: bool,
}

impl AppState {
    /// Whether this ingester's WAL is mirrored to object storage, i.e. whether
    /// a REMOTE drain may be the one that commits its segments.
    ///
    /// Decides whether local file movement is a valid proxy for "committed" —
    /// see [`wait_for_force_commit`].
    pub async fn wal_is_mirrored(&self) -> bool {
        if let Some(tenants) = self.tenants.as_ref() {
            return tenants.has_mirror().await;
        }
        self.writer.lock().await.has_mirror()
    }

    /// Convenience: wrap a `WalWriter` and set up a broadcast channel
    /// for SSE subscribers, all in one call.
    pub fn with_streaming(writer: WalWriter) -> Self {
        let (tx, _rx) = broadcast::channel(STREAM_BROADCAST_CAPACITY);
        Self {
            writer: Arc::new(Mutex::new(writer)),
            tenants: None,
            allowed_tenants: None,
            tenant_routing: TenantRouting::default(),
            max_tenants: 0,
            tenant_admission: Default::default(),
            backpressure: None,
            events_tx: Some(tx),
            tokens: None,
            oidc_verifier: None,
            rate_limiter: None,
            mem_guard: None,
            commit_force_timeout: Duration::from_secs(DEFAULT_COMMIT_FORCE_TIMEOUT_SECS),
            remote_wal_drain: true,
        }
    }

    /// Attach an RSS memory circuit breaker. The caller is responsible for
    /// spawning its sampler (see [`mem_guard::spawn_sampler`]).
    pub fn with_mem_guard(mut self, guard: Arc<mem_guard::MemoryGuard>) -> Self {
        self.mem_guard = Some(guard);
        self
    }

    pub fn with_commit_force_timeout(mut self, timeout: Duration) -> Self {
        self.commit_force_timeout = timeout;
        self
    }

    /// Enable the mpsc-fed backpressure-aware writer path. When set,
    /// the ingest handlers route every accepted batch through this
    /// [`backpressure::BackpressureRouter`] instead of locking
    /// `Mutex<WalWriter>`. A full lane returns 503 + `Retry-After`,
    /// rather than queueing behind the mutex until memory pressure
    /// builds. See `backpressure` module docs.
    ///
    /// Mutually consistent with `with_tenants` — if both are set, the
    /// backpressure router is used and `tenants` is ignored (the
    /// router owns per-tenant lanes itself). Mirror handles attached
    /// to `tenants` won't apply to the backpressure router; call
    /// [`backpressure::BackpressureRouter::set_mirror_handle`]
    /// instead.
    pub fn with_backpressure(mut self, bp: backpressure::BackpressureRouter) -> Self {
        self.backpressure = Some(Arc::new(bp));
        self
    }

    /// [`Self::with_backpressure`] for a router the caller already shares — the
    /// identity-refresh task holds one too.
    pub fn with_backpressure_arc(mut self, bp: Arc<backpressure::BackpressureRouter>) -> Self {
        self.backpressure = Some(bp);
        self
    }

    pub fn with_tokens(mut self, tokens: AuthTokens) -> Self {
        if tokens.is_empty() {
            self.tokens = None;
        } else {
            self.tokens = Some(Arc::new(tokens));
        }
        self
    }

    pub fn with_oidc_verifier(mut self, verifier: OidcVerifier) -> Self {
        self.oidc_verifier = Some(Arc::new(verifier));
        self
    }

    /// Opt into multi-tenant routing from the unverified `X-Scope-OrgID`
    /// header. See [`TenantRouting`].
    pub fn with_tenant_routing(mut self, routing: TenantRouting) -> Self {
        self.tenant_routing = routing;
        self
    }

    pub fn with_rate_limiter(mut self, rl: Arc<dyn rate_limit::RateBudget>) -> Self {
        self.rate_limiter = Some(rl);
        self
    }

    pub fn with_tenants(mut self, tenants: TenantWalRouter) -> Self {
        self.tenants = Some(Arc::new(tenants));
        self
    }

    /// Resolve a request to its writer + tenant identifier. Used by
    /// the ingest handlers: per-tenant mode looks the tenant up in
    /// [`TenantWalRouter`]; single-tenant mode returns the default
    /// writer.
    pub async fn writer_for_request(
        &self,
        req_tenant: Option<&str>,
    ) -> Result<(Arc<Mutex<WalWriter>>, String)> {
        let (writer, tenant, _) = self.writer_for_index_request(req_tenant, None).await?;
        Ok((writer, tenant))
    }

    /// Resolve a request to its writer + tenant + index identifiers.
    pub async fn writer_for_index_request(
        &self,
        req_tenant: Option<&str>,
        req_index: Option<&str>,
    ) -> Result<(Arc<Mutex<WalWriter>>, String, String)> {
        match &self.tenants {
            Some(router) => {
                let t = req_tenant.unwrap_or(DEFAULT_TENANT);
                let index = req_index.unwrap_or(EVENTS_INDEX_ID);
                let w = router.writer_for_index(t, index).await?;
                Ok((w, t.to_string(), index.to_string()))
            }
            None => Ok((
                self.writer.clone(),
                DEFAULT_TENANT.to_string(),
                EVENTS_INDEX_ID.to_string(),
            )),
        }
    }

    /// Resolve which tenant a request belongs to, applying the same
    /// `default` fallback the writer-router path uses.
    pub fn tenant_for_request(&self, req_tenant: Option<&str>) -> String {
        req_tenant.unwrap_or(DEFAULT_TENANT).to_string()
    }
}

