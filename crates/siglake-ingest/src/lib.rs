//! OTLP HTTP ingest server.
//!
//! Endpoints:
//!
//! - `POST /v1/logs` — OTLP/HTTP logs (protobuf or JSON, per `Content-Type`).
//!   Resource/scope/record attributes map onto [`Event`]
//!   (`host.name`→host, `service.name`/scope→source, record `sourcetype`/
//!   `index` attrs, body→`raw`).
//! - `GET  /api/v1/stream` — best-effort SSE tail of the ingest path. The tee
//!   sits BEFORE the WAL append, so a tailed event is not yet acknowledged.
//! - `GET  /healthz` — health probe.
//!
//! Tenancy is SINGLE-TENANT by default: every request routes to the `default`
//! tenant, and `X-Scope-OrgID` may name that tenant and nothing else. Two
//! things turn multi-tenant routing on, and both are explicit — a verified JWT
//! claim (`--oidc-tenant-claim`), which is the authority wherever it is
//! configured, or `--trust-scope-header`, which takes the client's word.
//! See [`TenantRouting`] and [`authorize_tenant`].
//!
//! Each request routes to a per-tenant [`WalWriter`] under
//! `<wal-root>/<tenant>/`, which the compactor commits to the matching Iceberg
//! namespace. An optional bearer-token allow-list gates auth, decoupled from
//! tenancy; with none configured the ingest is open.

