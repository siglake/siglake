#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, PartialOrd, Ord)]
enum CommitMode {
    Auto,
    #[default]
    WaitFor,
    Force,
}

impl CommitMode {
    fn as_label(self) -> &'static str {
        match self {
            Self::Auto => "auto",
            Self::WaitFor => "wait_for",
            Self::Force => "force",
        }
    }
}

#[derive(Clone, Copy, Debug, Default, Deserialize, utoipa::IntoParams)]
#[into_params(parameter_in = Query)]
struct CommitQuery {
    /// Durability the caller wants before the response returns. Overrides the
    /// `x-siglake-commit` header when both are present. Defaults to `wait_for`.
    ///
    /// An unrecognized value is rejected by axum's `Query` extractor with a
    /// bare `400`, not the usual error envelope.
    #[param(inline)]
    commit: Option<CommitQueryValue>,
}

#[derive(Clone, Copy, Debug, Deserialize, utoipa::ToSchema)]
#[serde(rename_all = "snake_case")]
enum CommitQueryValue {
    /// Opt-in page-cache mode. Acknowledge once the batch has been WRITTEN to the WAL —
    /// `write(2)`, not `fsync(2)`.
    ///
    /// The rows survive a process crash, an OOM kill and a pod restart, because
    /// the data is in the kernel page cache and the file outlives the process.
    /// They do NOT survive a node-level crash or power loss in the window before
    /// the kernel flushes.
    Auto,
    /// Acknowledge once the batch has been `fsync`ed to the WAL.
    ///
    /// Survives node crash and power loss. It does NOT wait for the rows to
    /// become queryable — the compactor commits asynchronously, so visibility
    /// follows on the drain's cadence (measured p50 ~5.5s). The previous
    /// "block until the rows are queryable" was simply wrong about what is
    /// awaited.
    WaitFor,
    /// Force an immediate commit and block until this ingester observes it.
    ///
    /// Requires a local drain that moves the segment out of this ingester's
    /// `sealed/` and `processing/` directories. It is refused with `400` when a
    /// remote catalog-claim drain consumes a mirrored WAL, because that commit
    /// is not observable here. May return `504` if the local commit does not
    /// land within `SIGLAKE_COMMIT_FORCE_TIMEOUT_SECS`.
    Force,
}

fn parse_commit_mode_value(raw: &str, source: &str) -> Result<CommitMode, String> {
    match raw.trim() {
        "auto" => Ok(CommitMode::Auto),
        "wait_for" => Ok(CommitMode::WaitFor),
        "force" => Ok(CommitMode::Force),
        _ => Err(format!(
            "invalid {source}: expected one of `auto`, `wait_for`, `force`"
        )),
    }
}

fn resolve_commit_mode(query: CommitQuery, raw_header: Option<&str>) -> Result<CommitMode, String> {
    match query.commit {
        Some(value) => Ok(match value {
            CommitQueryValue::Auto => CommitMode::Auto,
            CommitQueryValue::WaitFor => CommitMode::WaitFor,
            CommitQueryValue::Force => CommitMode::Force,
        }),
        None => raw_header
            .map(|raw| parse_commit_mode_value(raw, COMMIT_HEADER))
            .transpose()
            .map(|mode| mode.unwrap_or_default()),
    }
}

fn resolve_grpc_commit_mode(raw_header: Option<&str>) -> Result<CommitMode, String> {
    raw_header
        .map(|raw| parse_commit_mode_value(raw, COMMIT_HEADER))
        .transpose()
        .map(|mode| mode.unwrap_or_default())
}

