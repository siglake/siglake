/// Build the axum router. Public so integration tests can mount it without
/// going through [`serve`].
pub fn router(state: AppState) -> Router {
    let ingest = ingest_routes()
        .split_for_parts()
        .0
        .route_layer(middleware::from_fn_with_state(
            state.clone(),
            ingest_auth_middleware,
        ))
        // Rate-limit *before* auth so a flood of bad requests can't keep the
        // auth check hot. axum applies layers bottom-up, so the second
        // `route_layer` here runs first per request.
        .route_layer(middleware::from_fn_with_state(
            state.clone(),
            ingest_rate_limit_middleware,
        ));

    // Body cap: axum's 2 MB default rejects normal shipper batches with 413
    // (comparable engines cap ingest around 10 MiB; ES bulk clients commonly
    // send ~5 MiB). 16 MiB default, env-tunable.
    let body_limit = std::env::var("SIGLAKE_INGEST_MAX_BODY_BYTES")
        .ok()
        .and_then(|v| v.parse::<usize>().ok())
        .filter(|&n| n > 0)
        .unwrap_or(16 * 1024 * 1024);
    public_routes()
        .split_for_parts()
        .0
        .merge(ingest)
        .layer(axum::extract::DefaultBodyLimit::max(body_limit))
        // Per-request `tracing` span (http.method, http.uri, http.status).
        // With the OTel traces layer installed (`siglake_core::telemetry`), these
        // spans are forwarded as OTel spans automatically; no-op when OTel is off.
        .layer(tower_http::trace::TraceLayer::new_for_http())
        .with_state(state)
}

/// Token-bucket rate-limit middleware. Keys by the `Authorization`
/// token if present (so each ingest token gets its own budget); otherwise
/// keys by `X-Forwarded-For` (most ingester deployments sit behind an
/// LB); otherwise lumps anonymous callers into a single bucket. On
/// throttle returns `429` with a `Retry-After` header.
async fn ingest_rate_limit_middleware(
    State(state): State<AppState>,
    request: Request,
    next: Next,
) -> Response {
    let Some(rl) = state.rate_limiter.as_ref() else {
        return next.run(request).await;
    };
    let (key, key_kind) = rate_limit_key(&request, state.tenant_routing);
    match rl.try_acquire(&key).await {
        rate_limit::RateOutcome::Allowed => next.run(request).await,
        rate_limit::RateOutcome::Throttled { retry_after_secs } => {
            metrics::counter!(
                "siglake_ingest_rate_limit_rejected_total",
                "key_kind" => key_kind
            )
            .increment(1);
            let body = serde_json::json!({
                "text": "Too Many Requests",
                "code": 429,
                "retry_after_secs": retry_after_secs,
            });
            let mut resp = (StatusCode::TOO_MANY_REQUESTS, Json(body)).into_response();
            resp.headers_mut().insert(
                axum::http::header::RETRY_AFTER,
                axum::http::HeaderValue::from(retry_after_secs),
            );
            resp
        }
    }
}

/// The bucket a request's rate budget is charged to.
///
/// TENANT FIRST. The README's multi-tenancy section states "Rate budgets are
/// per-tenant", and they were not: the key was the bearer token, else the first
/// `X-Forwarded-For` hop, else the constant `"anonymous"` — the tenant was
/// never part of it. In the architecture siglake actually ships (one
/// cluster-wide token, tenancy by header) every tenant therefore shared ONE
/// bucket, so a single tenant's burst returned 429 to all of them; and behind a
/// load balancer that does not preserve XFF, an open-mode deployment collapsed
/// to one global `anonymous` bucket.
///
/// An operator sizing a shared cluster reads that sentence and relies on it.
///
/// ONLY WHERE THE HEADER MEANS SOMETHING. This middleware runs ahead of
/// authentication on purpose — it is what protects the auth path — so it reads
/// the header raw, before anything has decided whether this ingester routes on
/// it. On a single-tenant ingester it does not, and keying on it there would
/// hand every caller an unlimited supply of fresh buckets: vary the header,
/// vary the budget, land in the same `default` tenant regardless. So the tenant
/// half of the key applies only where the header selects a tenant.
fn rate_limit_key(request: &Request, routing: TenantRouting) -> (String, &'static str) {
    let headers = request.headers();
    if let Some(tenant) = (routing == TenantRouting::TrustHeader)
        .then(|| headers.get(TENANT_HEADER))
        .flatten()
        .and_then(|v| v.to_str().ok())
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        return (format!("tenant:{tenant}"), "tenant");
    }
    if let Some(tok) = headers
        .get(AUTHORIZATION)
        .and_then(|v| v.to_str().ok())
        .and_then(|s| s.strip_prefix("Bearer "))
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        return (format!("token:{tok}"), "token");
    }
    if let Some(ip) = headers
        .get("x-forwarded-for")
        .and_then(|v| v.to_str().ok())
        .and_then(|s| s.split(',').next())
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        return (format!("ip:{ip}"), "ip");
    }
    ("anonymous".to_string(), "anonymous")
}

/// Header carrying the tenant id (Grafana/Mimir/Loki convention). Absent ⇒ the
/// request routes to [`DEFAULT_TENANT`], and so does a present one unless this
/// ingester was told to route on it ([`TenantRouting`]). HTTP header names are
/// case-insensitive, so this matches `X-Scope-OrgID` regardless of casing; the
/// gRPC exporters read the same name out of the request metadata.
pub const TENANT_HEADER: &str = "x-scope-orgid";

/// Validate a client-supplied tenant id. The value becomes a WAL subdirectory
/// (`<root>/<tenant>/`) and an Iceberg namespace (`tenant_<id>`), so untrusted
/// input is restricted to a safe identifier — ASCII alphanumerics plus `-`/`_`,
/// 1..=128 chars — which forbids path traversal (`/`, `..`) by construction.
///
/// Re-exported from [`siglake_core::tenant`]: the query boundary applies the
/// same rule to its JWT tenant claim, and the two must agree on the answer or
/// the writer and the reader disagree about which namespace a tenant owns.
pub use siglake_core::tenant::sanitize_tenant;

/// The `X-Scope-OrgID` a request arrived with, as its transport saw it.
///
/// An HTTP header value that is not readable as text and a gRPC metadata value
/// that is not ASCII are the same fact, and neither may be quietly read as "no
/// header": that is how an unroutable value becomes a write to the default
/// tenant.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ScopeHeader<'a> {
    /// No tenant header on the request.
    Absent,
    /// Present, but the transport cannot read it as text.
    Unreadable,
    /// Present, with this raw (unvalidated) value.
    Value(&'a str),
}

/// Why the tenancy boundary refused a request, before any handler ran.
///
/// One type for both transports so an HTTP `403` and a gRPC `PermissionDenied`
/// cannot drift apart: each transport maps this, and neither decides it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TenancyRefusal {
    /// The request is malformed — `400` / `InvalidArgument`.
    BadRequest(String),
    /// No usable credential — `401` / `Unauthenticated`.
    Unauthorized(String),
    /// Authenticated (or not required), but not for this tenant — `403` /
    /// `PermissionDenied`.
    Forbidden(String),
}

impl TenancyRefusal {
    fn into_api_error(self) -> ApiError {
        match self {
            Self::BadRequest(msg) => ApiError::bad_request(msg),
            Self::Unauthorized(msg) => ApiError::unauthorized(msg),
            Self::Forbidden(msg) => ApiError::forbidden(msg),
        }
    }

    fn into_status(self) -> Status {
        match self {
            Self::BadRequest(msg) => Status::invalid_argument(msg),
            Self::Unauthorized(msg) => Status::unauthenticated(msg),
            Self::Forbidden(msg) => Status::permission_denied(msg),
        }
    }
}

/// Authenticate a request and decide which tenant it writes to — the one
/// tenancy decision on the ingest path, for every transport.
///
/// THIS USED TO BE HTTP-ONLY. The axum middleware verified OIDC and bound the
/// tenant to the verified claim; the OTLP/gRPC exporters resolved the tenant
/// straight out of the request metadata and checked nothing but the static
/// token list. So on an ingester configured with `--oidc-issuer` and
/// `--oidc-tenant-claim` — the configuration an operator reaches for precisely
/// to stop cross-tenant writes — the gRPC port accepted unauthenticated exports
/// and wrote them wherever `x-scope-orgid` said. Turning OIDC on hardened one
/// port and left the other open. Both transports now call this.
///
/// The order of the decision:
///
///  1. The tenant header is validated if present, whatever happens next: an
///     unusable value is a `400`, never a silent fallback to the default.
///  2. Credentials. With a verifier configured, a valid JWT is mandatory — a
///     missing or unverifiable one is a `401` and the request stops here.
///     Otherwise the static bearer-token list (which may be empty ⇒ open).
///  3. The tenant. A configured tenant claim is the authority: a token without
///     a usable one is refused (token validity is not tenant authorization),
///     and a header naming a different tenant is refused rather than ignored.
///     With no claim configured, [`TenantRouting`] decides — single-tenant by
///     default, so a header naming another tenant is refused.
///  4. `--allowed-tenants`, against the tenant actually resolved. It is checked
///     last and on the FINAL value: checking the header's value and then
///     replacing it with the claim, as this did, left a claimed tenant
///     unbounded by the allow-list.
///  5. `--max-tenants`, against the same final value, for a tenant this process
///     has not admitted before. Last because it is the backstop: a tenant the
///     allow-list would refuse must not spend a slot under the cap.
///
/// Refusals are counted by `siglake_ingest_tenant_denied_total`
/// (`reason="claim_missing"` / `"claim_invalid"` / `"header_mismatch"` /
/// `"header_not_trusted"` / `"not_allowed"` / `"at_capacity"`). Nothing for the
/// refused tenant is created first: no lane, no writer, no metric label.
pub async fn authorize_tenant(
    state: &AppState,
    scope: ScopeHeader<'_>,
    raw_auth: Option<&str>,
) -> Result<String, TenancyRefusal> {
    let header_tenant = match scope {
        ScopeHeader::Absent => None,
        ScopeHeader::Unreadable => {
            return Err(TenancyRefusal::BadRequest(format!(
                "invalid {TENANT_HEADER} tenant id (use [A-Za-z0-9_-], 1..=128 chars)"
            )))
        }
        ScopeHeader::Value(raw) => match resolve_tenant_value(Some(raw)) {
            Ok(tenant) => Some(tenant),
            Err(msg) => return Err(TenancyRefusal::BadRequest(msg)),
        },
    };

    // Auth: OIDC takes precedence over the static token allow-list.
    let mut verified_tenant = None;
    if let Some(verifier) = &state.oidc_verifier {
        let token = match raw_auth
            .and_then(|s| s.strip_prefix("Bearer "))
            .map(str::trim)
        {
            Some(t) if !t.is_empty() => t,
            _ => {
                return Err(TenancyRefusal::Unauthorized(
                    "missing Authorization: Bearer <jwt>".to_string(),
                ))
            }
        };
        let claims = match verifier.verify(token).await {
            Ok(claims) => claims,
            Err(e) => {
                tracing::debug!(error = %e, "ingest oidc verify failed");
                return Err(TenancyRefusal::Unauthorized(format!(
                    "oidc verify failed: {e}"
                )));
            }
        };
        // The claims used to be DISCARDED here — verified, then thrown away,
        // which is what left the header as the sole authority even under OIDC.
        if verifier.has_tenant_claim() {
            let Some(claimed) = verifier.extract_tenant(&claims) else {
                metrics::counter!("siglake_ingest_tenant_denied_total",
                    "reason" => "claim_missing")
                .increment(1);
                return Err(TenancyRefusal::Forbidden(
                    "this ingester derives the tenant from a JWT claim, and the token carries none"
                        .to_string(),
                ));
            };
            let claimed = match resolve_tenant_value(Some(&claimed)) {
                Ok(t) => t,
                Err(msg) => {
                    metrics::counter!("siglake_ingest_tenant_denied_total",
                        "reason" => "claim_invalid")
                    .increment(1);
                    return Err(TenancyRefusal::Forbidden(format!(
                        "tenant claim is unusable: {msg}"
                    )));
                }
            };
            if header_tenant.is_some() && header_tenant.as_deref() != Some(claimed.as_str()) {
                metrics::counter!("siglake_ingest_tenant_denied_total",
                    "reason" => "header_mismatch")
                .increment(1);
                return Err(TenancyRefusal::Forbidden(format!(
                    "{TENANT_HEADER} does not match the tenant this token is for"
                )));
            }
            verified_tenant = Some(claimed);
        }
    } else if let Err(msg) = ensure_authorized(state.tokens.as_deref(), raw_auth) {
        return Err(TenancyRefusal::Unauthorized(msg));
    }

    let tenant = match (verified_tenant, state.tenant_routing) {
        (Some(claimed), _) => claimed,
        (None, TenantRouting::TrustHeader) => {
            header_tenant.unwrap_or_else(|| DEFAULT_TENANT.to_string())
        }
        (None, TenantRouting::SingleTenant) => match header_tenant {
            // Naming the tenant this ingester already writes to is a no-op, so
            // a client that always sends the header keeps working.
            Some(t) if t == DEFAULT_TENANT => t,
            Some(_) => {
                metrics::counter!("siglake_ingest_tenant_denied_total",
                    "reason" => "header_not_trusted")
                .increment(1);
                return Err(TenancyRefusal::Forbidden(format!(
                    "this ingester is single-tenant: {TENANT_HEADER} cannot select a tenant. Bind \
                     tenancy to a verified identity with --oidc-tenant-claim, or pass \
                     --trust-scope-header if this ingester sits behind a gateway that sets the \
                     header"
                )));
            }
            None => DEFAULT_TENANT.to_string(),
        },
    };

    if let Some(allowed) = &state.allowed_tenants {
        if !allowed.contains(&tenant) {
            metrics::counter!("siglake_ingest_tenant_denied_total",
                "reason" => "not_allowed")
            .increment(1);
            return Err(TenancyRefusal::Forbidden(format!(
                "tenant `{tenant}` is not in this ingester's allowed set"
            )));
        }
    }
    // REFUSED BEFORE ANYTHING IS CREATED, as with the lane cap: past the cap no
    // writer opens, no directory is made, no metric label value exists and no
    // row is published. A tenant already admitted keeps writing at capacity.
    if !state.tenant_admission.admit(&tenant, state.max_tenants) {
        metrics::counter!("siglake_ingest_tenant_denied_total",
            "reason" => "at_capacity")
        .increment(1);
        return Err(TenancyRefusal::Forbidden(format!(
            "tenant limit reached ({} tenants): refusing novel tenant `{tenant}`. The tenants \
             already writing here are unaffected. Raise --max-tenants, or name the tenants you \
             expect with --allowed-tenants.",
            state.max_tenants
        )));
    }
    Ok(tenant)
}

/// [`authorize_tenant`] for the HTTP surface: attaches a [`ResolvedTenant`]
/// extension so downstream handlers pick the right per-tenant writer. Health
/// probes bypass this middleware (separate router segment).
async fn ingest_auth_middleware(
    State(state): State<AppState>,
    mut request: Request,
    next: Next,
) -> Response {
    let scope = match request.headers().get(TENANT_HEADER) {
        None => ScopeHeader::Absent,
        Some(value) => match value.to_str() {
            Ok(raw) => ScopeHeader::Value(raw),
            Err(_) => ScopeHeader::Unreadable,
        },
    };
    let raw_auth = request
        .headers()
        .get(AUTHORIZATION)
        .and_then(|value| value.to_str().ok());
    let tenant = match authorize_tenant(&state, scope, raw_auth).await {
        Ok(tenant) => tenant,
        Err(refusal) => return refusal.into_api_error().into_response(),
    };

    request.extensions_mut().insert(ResolvedTenant(tenant));
    next.run(request).await
}

/// Bind and serve on `addr`. Returns when the server stops.
///
/// Graceful shutdown (Phase 4.13d): on SIGINT/SIGTERM the server
/// stops accepting new connections, waits for in-flight requests
/// to complete, then returns. The caller (CLI) is responsible for
/// draining any `BackpressureRouter` *after* this returns — the
/// router owns per-tenant writer tasks whose mpsc senders must
/// drop *only* once every ingest handler has finished handing off
/// its batch.
pub async fn serve(addr: SocketAddr, state: AppState) -> Result<()> {
    let listener = tokio::net::TcpListener::bind(addr)
        .await
        .with_context(|| format!("bind {addr}"))?;
    let bound = listener.local_addr()?;
    tracing::info!(addr = %bound, "siglake-ingest HTTP server listening");
    axum::serve(listener, router(state))
        .with_graceful_shutdown(shutdown_signal())
        .await?;
    tracing::info!("siglake-ingest HTTP server stopped accepting connections");
    Ok(())
}

pub async fn serve_with_otlp_grpc(
    addr: SocketAddr,
    otlp_grpc_addr: Option<SocketAddr>,
    state: AppState,
) -> Result<()> {
    let Some(otlp_grpc_addr) = otlp_grpc_addr else {
        return serve(addr, state).await;
    };

    let listener = tokio::net::TcpListener::bind(addr)
        .await
        .with_context(|| format!("bind {addr}"))?;
    let bound = listener.local_addr()?;
    tracing::info!(addr = %bound, "siglake-ingest HTTP server listening");
    tracing::info!(addr = %otlp_grpc_addr, "siglake-ingest OTLP gRPC server listening");

    let (shutdown_rx, shutdown_task) = spawn_shutdown_broadcaster();
    let http_state = state.clone();
    let traces_state = state.clone();
    let grpc_shutdown = shutdown_rx.clone();
    let grpc = async move {
        tonic::transport::Server::builder()
            .add_service(LogsServiceServer::new(OtlpGrpcLogsService::new(state)))
            .add_service(TraceServiceServer::new(OtlpGrpcTracesService::new(
                traces_state,
            )))
            .serve_with_shutdown(otlp_grpc_addr, await_shutdown(grpc_shutdown))
            .await
            .map_err(anyhow::Error::from)
    };
    let http = async move {
        axum::serve(listener, router(http_state))
            .with_graceful_shutdown(await_shutdown(shutdown_rx))
            .await
            .map_err(anyhow::Error::from)
    };

    let result = tokio::try_join!(http, grpc).map(|_| ());
    shutdown_task.abort();
    if result.is_ok() {
        tracing::info!("siglake-ingest HTTP server stopped accepting connections");
        tracing::info!("siglake-ingest OTLP gRPC server stopped accepting connections");
    }
    result
}

/// Future that resolves on the first of SIGINT (ctrl-c) or
/// SIGTERM (the kube-default termination signal). Composed into
/// `axum::serve().with_graceful_shutdown(...)`.
async fn shutdown_signal() {
    use tokio::signal::unix::{signal, SignalKind};
    let ctrl_c = async {
        if let Ok(()) = tokio::signal::ctrl_c().await {
            tracing::info!(signal = "SIGINT", "shutdown signal received");
        }
    };
    let sigterm = async {
        match signal(SignalKind::terminate()) {
            Ok(mut s) => {
                s.recv().await;
                tracing::info!(signal = "SIGTERM", "shutdown signal received");
            }
            Err(e) => {
                // No SIGTERM handler — fall through to ctrl_c only.
                tracing::warn!(error = %e, "SIGTERM handler unavailable");
                std::future::pending::<()>().await;
            }
        }
    };
    tokio::select! {
        _ = ctrl_c => {}
        _ = sigterm => {}
    }
}

fn spawn_shutdown_broadcaster() -> (watch::Receiver<bool>, tokio::task::JoinHandle<()>) {
    let (tx, rx) = watch::channel(false);
    let handle = tokio::spawn(async move {
        shutdown_signal().await;
        let _ = tx.send(true);
    });
    (rx, handle)
}

async fn await_shutdown(mut rx: watch::Receiver<bool>) {
    if *rx.borrow() {
        return;
    }
    let _ = rx.changed().await;
}

