async fn post_es_bulk_inner(
    state: AppState,
    commit_mode: CommitMode,
    tenant: Option<axum::extract::Extension<ResolvedTenant>>,
    path_index: Option<String>,
    body: Bytes,
) -> Result<Response, ApiError> {
    let _in_flight = InFlightGuard::new("es_bulk");
    let start = Instant::now();
    let tenant_id = tenant
        .as_ref()
        .map(|resolved| resolved.0 .0.clone())
        .unwrap_or_else(|| DEFAULT_TENANT.to_string());
    let path_index = path_index.as_deref();
    if let Some(guard) = state.mem_guard.as_ref() {
        if guard.is_over_limit() {
            return Ok(mem_breaker_response("es_bulk"));
        }
    }
    let parsed = parse_es_bulk_request(body.as_ref(), path_index)?;
    metrics::counter!("siglake_ingest_commit_total", "mode" => commit_mode.as_label()).increment(1);
    for (index_id, events) in parsed.groups {
        ingest_events(
            &state,
            &tenant_id,
            &index_id,
            events,
            commit_mode,
            "es_bulk",
        )
        .await?;
    }
    let index_metric = bulk_metric_index(&parsed.items);
    let errors = parsed.items.iter().any(|item| item.status >= 400);
    let response = serde_json::json!({
        "took": start.elapsed().as_millis() as u64,
        "errors": errors,
        "items": parsed.items.into_iter().map(BulkItemResponse::into_value).collect::<Vec<_>>(),
    });
    Ok(bulk_success_response(
        "es_bulk",
        &tenant_id,
        &index_metric,
        start,
        parsed.accepted,
        response,
    ))
}

